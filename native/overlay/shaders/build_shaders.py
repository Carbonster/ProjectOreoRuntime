"""Compiles the overlay's shaders into a C++ header, so they travel inside the DLL.

Needs glslc from the Vulkan SDK. Only run when a shader changes; the header is committed,
so building the Runtime itself needs no shader compiler.

    python native/overlay/shaders/build_shaders.py
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parent / "src" / "render" / "rml" / "shader_binaries.h"
SHADERS = sorted(p for p in HERE.iterdir() if p.suffix in (".vert", ".frag"))


def compile_to_words(source: Path, glslc: str) -> list[int]:
    with tempfile.TemporaryDirectory() as tmp:
        spv = Path(tmp) / "out.spv"
        subprocess.run([glslc, "-O", "--target-env=vulkan1.0", str(source), "-o", str(spv)],
                       check=True)
        data = spv.read_bytes()
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def array_name(source: Path) -> str:
    stage = "Vert" if source.suffix == ".vert" else "Frag"
    return "k" + "".join(part.capitalize() for part in source.stem.split("_")) + stage


def main() -> int:
    glslc = shutil.which("glslc")
    if not glslc:
        print("glslc not found; install the Vulkan SDK.", file=sys.stderr)
        return 1
    lines = [
        "// Generated by native/overlay/shaders/build_shaders.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace shader_binaries {",
        "",
    ]
    for source in SHADERS:
        words = compile_to_words(source, glslc)
        lines.append(f"// {source.name}")
        lines.append(f"inline const uint32_t {array_name(source)}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace shader_binaries")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(HERE.parent.parent.parent)} ({len(SHADERS)} shaders)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
